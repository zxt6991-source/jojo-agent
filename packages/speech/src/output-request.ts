export { isExplicitReadAloudRequest, shouldDisableAutoRead } from '@desktop-agent/contracts';

export function desktopSpeechInstructions(enabled: boolean, readAloud: boolean): string[] {
  const capability = enabled
    ? '你运行在 Jojo 桌面客户端，客户端已启用本地 TTS 朗读，可以把已提交的助手正文合成为声音并播放。普通文字提问只用文字回复，不自动进入语音模式；文字输入同样可以请求朗读，但仅在用户明确要求时为本轮出声。以本轮能力状态为准，不沿用历史中“未启用”的说明。不要声称“这里只支持文字”“没法出声”“无法播放音频”或让用户另找 TTS 工具。模型负责提供正文，实际合成和播放由客户端完成；在收到实际播放结果前，不要宣称用户已经听到或播放已完成。'
    : '你运行在 Jojo 桌面客户端，客户端具备本地 TTS 朗读功能，但当前语音尚未启用。用户要求朗读时可提供正文，并简短引导到语音设置开启语音并保存；不需要先录音或完成试听测试。不要声称客户端没有语音能力，也不要宣称已经播放。';
  return [capability, ...(readAloud && enabled ? [
    '用户在本轮明确请求出声朗读。客户端会为本轮完整正文发起一次朗读，先准备好全部音频再连续播放到全文结束，不改变后续自动朗读偏好。优先直接给出所请求的诗词、文章或其他可朗读正文，保留原文全部句子；多首或多篇按请求顺序依次给出正文，不添加开场白、结尾点评或已交给客户端播放的说明。不要用口语摘要替代，不添加断句标记、重音标记、SSML、朗读教程或能力免责声明。若内容不明确才追问；若无法提供全文，直接说明具体原因。'
  ] : [])];
}
